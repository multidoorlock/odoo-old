CENT = Decimal('0.01')
FOUR_DP = Decimal('0.0001')


def D(value):
    return Decimal(str(value or 0))


def money(value):
    return D(value).quantize(CENT, rounding=ROUND_HALF_UP)


def four(value):
    return D(value).quantize(FOUR_DP, rounding=ROUND_HALF_UP)


def fail(message):
    raise RuntimeError('PAYROLL MIGRATION ABORTED: ' + message)


def info(message):
    print('[PAYROLL-MIGRATION] ' + message)


def payslip_line_signature(slip):
    parts = []
    for line in slip.line_ids.sorted(key=lambda x: x.id):
        parts.append(
            f"{line.id}|{line.salary_rule_id.id}|{line.code or ''}|"
            f"{money(line.amount):.2f}|{money(line.quantity):.2f}|"
            f"{four(line.rate):.4f}|{money(line.total):.2f}"
        )
    return sha256('\n'.join(parts).encode('utf-8')).hexdigest()


def table_guard(table):
    """Read-only fingerprint used only to prove this script didn't touch unrelated domains."""
    env.cr.execute(
        f'SELECT count(*), COALESCE(max(write_date)::text, \'\') FROM {table}'
    )
    return tuple(env.cr.fetchone())


def build_target_split_specs():
    """Translate source split history to the reconciliation-native target representation."""
    target = []
    found_normalization = False
    for legacy_id, payment_id, sequence, amount_s, payslip_id in HISTORICAL_SPLITS:
        amount = Decimal(amount_s)
        if legacy_id == NORMALIZED_LEGACY_SPLIT_ID:
            if payment_id != 525 or sequence != 1 or payslip_id != 81 or amount != Decimal('2750.00'):
                fail('Legacy normalization source row 561 no longer matches the verified backup snapshot.')
            target.append({
                'legacy_id': legacy_id,
                'payment_id': payment_id,
                'sequence': 1,
                'amount': amount - NORMALIZED_EXCESS,
                'payslip_id': payslip_id,
                'kind': 'legacy-normalized-applied',
            })
            target.append({
                'legacy_id': '561-open-excess',
                'payment_id': payment_id,
                'sequence': 2,
                'amount': NORMALIZED_EXCESS,
                'payslip_id': None,
                'kind': 'legacy-normalized-open',
            })
            found_normalization = True
        else:
            target.append({
                'legacy_id': legacy_id,
                'payment_id': payment_id,
                'sequence': sequence,
                'amount': amount,
                'payslip_id': payslip_id,
                'kind': 'legacy',
            })
    if not found_normalization:
        fail('Required legacy overpayment normalization row was not found.')
    return target


